    """Исключение, вызываемое, когда вакансия не найдена.

    Это исключение может использоваться для обработки ситуаций,
    когда запрос на получение вакансий не возвращает никаких результатов.
    """

    def __init__(self, message: str = "Вакансии не найдены.") -> None:
        """Инициализация исключения VacancyNotFoundError.

        Аргументы:
            message (str): Сообщение, описывающее ошибку. По умолчанию используется
            сообщение о том, что вакансии не найдены.
        """
        self.message = message
        super().__init__(self.message)
