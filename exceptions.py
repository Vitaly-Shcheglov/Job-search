class ZeroQuantityError(Exception):
    """Исключение, вызываемое при попытке установить количество в ноль.

    Это исключение может использоваться в ситуациях, когда необходимо предотвратить добавление
    товара или элемента с нулевым количеством в какое-либо хранилище или список.
    """

    def __init__(self, message: str = "Товар с нулевым количеством не может быть добавлен.") -> None:
        """Инициализация исключения ZeroQuantityError.

        Аргументы:
            message (str): Сообщение, описывающее ошибку. По умолчанию используется
            сообщение о нулевом количестве товара.
        """
        self.message = message
        super().__init__(self.message)


